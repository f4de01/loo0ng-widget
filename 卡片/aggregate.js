// 聚合：把一次扫描的结果算成卡片上每案一行。
//
// 纯模块：不碰 DOM、不读文件、不起进程。页面调它，它不回头调页面。
// 原型答完题之后，整块抬进实现的就是这个文件。
//
// 边界（ADR-0029）：只做聚合，不做判定。这里出现的每个值，要么直接取自引擎算好的
// 字段，要么是对那些字段的计数、排序、取第一个。任何需要看「条目」才能得出的结论，
// 都必须由引擎先算好再交给这里。

export const 支持的格式版本 = 2;

export class 格式版本不合 extends Error {
  constructor(实际) {
    super(`图视图.json 的格式版本是 ${实际}，这张卡片只认 ${支持的格式版本}`);
    this.name = '格式版本不合';
    this.实际 = 实际;
  }
}

/** 一个案件的一份视图 -> 卡片上的一行。 */
export function 一行(目录名, 视图) {
  if (视图?.格式版本 !== 支持的格式版本) {
    throw new 格式版本不合(视图?.格式版本);
  }

  const 节点 = 视图.模块.flatMap(m => m.节点);
  const 计数 = 状态 => 节点.filter(n => n.状态 === 状态).length;

  // 「当前模块」：图序里第一个引擎算作「进行中」的模块。状态是引擎算的，这里只挑第一个。
  const 当前模块 = 视图.模块.find(m => m.状态 === '进行中')?.标题 ?? null;

  // 「下一个」：前方的第一个节点。前方本身也是引擎算好的。
  const 下一个 = 视图.前方?.[0]?.节点?.[0]?.标题 ?? null;

  // 「待看」：文书里还扫得出高亮的节点。高亮是引擎算的一列提示，不是确认。
  const 待看 = 节点.filter(n => n.高亮 === '未清').map(n => n.标题);

  return {
    目录名,
    生成时间: 视图.生成时间,
    当前模块,
    下一个,
    待看,
    进度: {
      总数: 节点.length,
      已确认: 计数('已确认'),
      已生成: 计数('已生成'),
      未生成: 计数('未生成'),
      不适用: 计数('不适用'),
    },
  };
}

/** 一次扫描的全部结果 -> 排好序的若干行，读不出的单独归一类。 */
export function 汇总(扫描结果) {
  const 行 = [];
  const 读不出 = [];

  for (const 案件 of 扫描结果.案件 ?? []) {
    if (案件.错误) {
      读不出.push({ 目录名: 案件.目录名, 路径: 案件.路径, 原因: 案件.错误 });
      continue;
    }
    try {
      行.push({ ...一行(案件.目录名, 案件.视图), 路径: 案件.路径 });
    } catch (e) {
      读不出.push({ 目录名: 案件.目录名, 路径: 案件.路径, 原因: e.message });
    }
  }

  // 排序是呈现的一部分，ADR-0029 把呈现整块推后了。这里先按「有待看的排前面，
  // 其余按目录名」摆着，等呈现那一轮再定，不要把它当裁定。
  行.sort((a, b) => {
    const d = (b.待看.length > 0) - (a.待看.length > 0);
    return d !== 0 ? d : a.目录名.localeCompare(b.目录名, 'zh');
  });

  return { 行, 读不出, 扫描时间: 扫描结果.扫描时间, 根目录: 扫描结果.根目录 ?? [] };
}
